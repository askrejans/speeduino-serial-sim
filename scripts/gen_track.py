#!/usr/bin/env python3
"""Generate include/TrackData.h from a closed circuit outline.

The outline (WGS-84 lat/lon, OpenStreetMap) is rounded with Chaikin corner
cutting, resampled along its length and turned into a speed envelope: the
grip-limited corner speed at every node, then a backward braking pass so the
driver model knows how fast it may be at each point. Acceleration is left to
the live vehicle model, because it depends on gear, torque and drag.

The same approach as the G86 app's realistic demo sessions
(test/helpers/realistic_session.dart).

    python3 scripts/gen_track.py data/tracks/bikernieki.json include/TrackData.h
"""
import json
import math
import sys

EARTH = 6371000.0
G = 9.81
LAT_G = 1.05     # cornering grip of a road-legal track car on semi-slicks
BRAKE_G = 0.95   # sustained braking
VMAX = 230 / 3.6
STEPS = {"FULL": 5.0, "COMPACT": 10.0}  # metres between nodes


def dist(a, b):
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    dp, dl = p2 - p1, math.radians(b[1] - a[1])
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * EARTH * math.asin(min(1.0, math.sqrt(h)))


def bearing(a, b):
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    dl = math.radians(b[1] - a[1])
    y = math.sin(dl) * math.cos(p2)
    x = math.cos(p1) * math.sin(p2) - math.sin(p1) * math.cos(p2) * math.cos(dl)
    return (math.degrees(math.atan2(y, x)) + 360) % 360


def turn(f, t):
    return (t - f + 540) % 360 - 180


def chaikin(pts, n):
    for _ in range(n):
        out = []
        for i, a in enumerate(pts):
            b = pts[(i + 1) % len(pts)]
            out.append([a[0] * .75 + b[0] * .25, a[1] * .75 + b[1] * .25])
            out.append([a[0] * .25 + b[0] * .75, a[1] * .25 + b[1] * .75])
        pts = out
    return pts


def resample(pts, step):
    ring = pts + [pts[0]]
    cum = [0.0]
    for i in range(1, len(ring)):
        cum.append(cum[-1] + dist(ring[i - 1], ring[i]))
    total = cum[-1]
    n = int(round(total / step))
    step = total / n  # exact wrap: node n coincides with node 0
    nodes, seg = [], 0
    for k in range(n):
        s = k * step
        while seg < len(cum) - 2 and cum[seg + 1] < s:
            seg += 1
        t = (s - cum[seg]) / max(1e-9, cum[seg + 1] - cum[seg])
        a, b = ring[seg], ring[seg + 1]
        nodes.append([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t])
    return nodes, total, step


def profile(outline, step):
    nodes, total, step = resample(chaikin(outline, 3), step)
    n = len(nodes)
    chord = max(1, int(round(15 / step)))
    heading = [bearing(nodes[(i - chord) % n], nodes[(i + chord) % n]) for i in range(n)]
    local = [abs(turn(heading[i], heading[(i + 1) % n])) * math.pi / 180 / step for i in range(n)]
    win = max(1, int(round(25 / step)))
    curv = [max(local[(i + j) % n] for j in range(-win, win + 1)) for i in range(n)]
    v = [min(VMAX, VMAX if c < 1e-5 else math.sqrt(LAT_G * G / c)) for c in curv]
    for _ in range(2):  # braking pass backwards, twice so it wraps the start line
        for i in range(n - 1, -1, -1):
            nxt = v[(i + 1) % n]
            v[i] = min(v[i], math.sqrt(nxt * nxt + 2 * BRAKE_G * G * step))
    return nodes, heading, v, total, step


def local_xy(nodes):
    lat0, lon0 = nodes[0]
    kx = EARTH * math.cos(math.radians(lat0)) * math.pi / 180
    ky = EARTH * math.pi / 180
    return [(round((p[1] - lon0) * kx), round((p[0] - lat0) * ky)) for p in nodes]


def table(name, ctype, values, per_line=20):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(x) for x in values[i:i + per_line]) + ",")
    return f"static const {ctype} {name}[] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


def main(src, dst):
    track = json.load(open(src, encoding="utf-8"))
    out = [
        "// Generated by scripts/gen_track.py — do not edit.",
        f"// {track['name']}, {track['location']}.",
        f"// Track data {track['attribution']}, {track['license']} ({track['licenseUrl']}).",
        f"// Envelope: {LAT_G} g cornering, {BRAKE_G} g braking.",
        "#pragma once",
        "#include <stdint.h>",
        "#include \"Progmem.h\"",
        "",
        f"#define TRACK_NAME \"{track['name']}\"",
        f"static const double TRACK_ORIGIN_LAT = {track['points'][0][0]};",
        f"static const double TRACK_ORIGIN_LON = {track['points'][0][1]};",
        "",
    ]
    for key, step in STEPS.items():
        nodes, heading, v, total, real_step = profile(track["points"], step)
        guard = "#if defined(TRACK_COMPACT)" if key == "COMPACT" else "#if !defined(TRACK_COMPACT)"
        out += [
            guard,
            f"static const uint16_t TRACK_NODES = {len(nodes)};",
            f"static const float TRACK_LENGTH_M = {total:.1f}f;",
            f"static const float TRACK_STEP_M = {real_step:.5f}f;",
            "// Fastest allowed speed at each node, km/h (corner limit + braking).",
            table("trackEnvelopeKmh", "uint8_t", [min(255, round(x * 3.6)) for x in v]),
            "// Driving direction at each node, 256 steps per turn (0 = north).",
            table("trackHeading", "uint8_t", [round(h / 360 * 256) % 256 for h in heading]),
        ]
        if key == "FULL":
            xy = local_xy(nodes)[::4]
            out += [
                "#if defined(TRACK_OUTLINE)",
                f"static const uint16_t TRACK_OUTLINE_POINTS = {len(xy)};",
                "// Outline every 4th node, metres east/north of the origin.",
                table("trackOutline", "int16_t", [c for p in xy for c in p]),
                "#endif",
            ]
        out += ["#endif", ""]
        lap = sum(real_step / max(1.0, x) for x in v)
        print(f"{key}: {len(nodes)} nodes, {total:.0f} m, envelope-only lap {lap:.1f} s, "
              f"min {min(v) * 3.6:.0f} km/h, max {max(v) * 3.6:.0f} km/h", file=sys.stderr)
    open(dst, "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
